export interface BuildDatasheetCatalogOptions {
  apiUrl?: string
  fetch?: typeof globalThis.fetch
  /** Defaults to lib/generated-bundled-parts.ts; false returns data without writing. */
  outputPath?: string | false
  compile?: (part: DatasheetSnapshotPart) => BundledPart
  log?: (message: string) => void
  concurrency?: number
  requestTimeoutMs?: number
  deadlineMs?: number
  onResponse?: (
    path: string,
    query: Record<string, string>,
    body: unknown,
  ) => Promise<void>
}

export interface DatasheetBuildExclusion {
  datasheet_id: string
  chip_name: string
  reason: string
  detail?: string
}

export interface DatasheetCatalogBuildResult {
  parts: BundledPart[]
  moduleText: string
  jsonBytes: number
  gzipBytes: number
  listedCount: number
  includedCount: number
  excludedCount: number
  exclusionCounts: Record<string, number>
  exclusions: DatasheetBuildExclusion[]
}

interface DatasheetSummary {
  datasheet_id: string
  chip_name: string
}

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0)
const invalid = (message: string): never => {
  throw new Error(`Datasheet build failed: ${message}`)
}

const object = (value: unknown, label: string): Record<string, unknown> => {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    return invalid(`${label} must be an object`)
  }
  return value as Record<string, unknown>
}

const string = (value: unknown, label: string, allowEmpty = false): string => {
  if (typeof value !== "string" || (!allowEmpty && !value.trim())) {
    return invalid(
      `${label} must be a string${allowEmpty ? "" : " with content"}`,
    )
  }
  return value
}

const strings = (value: unknown, label: string): string[] => {
  if (!Array.isArray(value)) return invalid(`${label} must be an array`)
  return value.map((entry) => string(entry, `${label} entry`))
}

const json = (value: unknown, label: string): JsonValue => {
  if (
    value === null ||
    typeof value === "string" ||
    typeof value === "boolean"
  ) {
    return value
  }
  if (typeof value === "number" && Number.isFinite(value)) return value
  if (Array.isArray(value)) return value.map((entry) => json(entry, label))
  const input = object(value, label)
  return Object.fromEntries(
    Object.entries(input).map(([key, entry]) => [
      key,
      json(entry, `${label}.${key}`),
    ]),
  )
}

/** Canonical object keys, while preserving meaningful ordering inside value arrays. */
const canonical = (value: unknown): unknown => {
  if (Array.isArray(value)) return value.map(canonical)
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .sort(([a], [b]) => compare(a, b))
        .map(([key, entry]) => [key, canonical(entry)]),
    )
  }
  return value
}

const serialize = (value: unknown): string =>
  `${JSON.stringify(canonical(value), null, 2)}\n`

/** Store only validated runtime parts, with no generated TSX or raw datasheet descriptions. */
export const encodeBundledParts = (
  parts: readonly BundledPart[],
): {
  moduleText: string
  jsonBytes: number
  gzipBytes: number
} => {
  const jsonBytes = strToU8(`${JSON.stringify(canonical(parts))}\n`)
  const compressed = gzipSync(jsonBytes, { mtime: 0 })
  const base64 = Buffer.from(compressed).toString("base64")
  const chunks = base64.match(/.{1,120}/g) ?? []
  return {
    moduleText: `// Generated by scripts/build-datasheets.ts during the build.\nexport const bundledPartsGzipBase64 = [\n${chunks.map((chunk) => `  ${JSON.stringify(chunk)},`).join("\n")}\n].join("")\n`,
    jsonBytes: jsonBytes.length,
    gzipBytes: compressed.length,
  }
}

/** A single staged rename preserves the previous generated module on write failure. */
export const writeBundledPartsModule = async (
  outputPath: string,
  moduleText: string,
  renameFile: (from: string, to: string) => Promise<void> = rename,
): Promise<void> => {
  const destination = resolve(outputPath)
  const directory = dirname(destination)
  await mkdir(directory, { recursive: true })
  const staging = await mkdtemp(join(directory, ".datasheets-build-"))
  try {
    const stagedFile = join(staging, "bundled-parts.ts")
    await writeFile(stagedFile, moduleText)
    await renameFile(stagedFile, destination)
  } finally {
    await rm(staging, { recursive: true, force: true })
  }
}

const parseList = (value: unknown): DatasheetSummary[] => {
  const body = object(value, "list response")
  if (!Array.isArray(body.datasheets) || body.datasheets.length === 0) {
    return invalid("list response must contain a non-empty datasheets array")
  }
  if (Object.keys(body).some((key) => key !== "datasheets")) {
    return invalid(
      "list response has unrecognized completeness or pagination metadata",
    )
  }
  const ids = new Set<string>()
  const names = new Set<string>()
  const entries = body.datasheets.map((entry) => {
    const row = object(entry, "list datasheet")
    const datasheet_id = string(row.datasheet_id, "datasheet_id")
    const chip_name = string(row.chip_name, "chip_name")
    if (
      datasheet_id !== datasheet_id.trim() ||
      chip_name !== chip_name.trim()
    ) {
      return invalid("list identifiers must be trimmed")
    }
    if (ids.has(datasheet_id))
      return invalid(`duplicate datasheet_id ${datasheet_id}`)
    if (names.has(chip_name.toUpperCase()))
      return invalid(`duplicate chip_name ${chip_name}`)
    ids.add(datasheet_id)
    names.add(chip_name.toUpperCase())
    return { datasheet_id, chip_name }
  })
  return entries.sort((a, b) => compare(a.datasheet_id, b.datasheet_id))
}

const errorDetail = (error: unknown): string =>
  (error instanceof Error ? error.message : String(error))
    .replace(/[\x00-\x1f\x7f]/g, " ")
    .replace(/\s+/g, " ")
    .slice(0, 240)

const parsePart = (
  value: unknown,
  summary: DatasheetSummary,
): {
  part?: DatasheetSnapshotPart
  reason?: string
  detail?: string
} => {
  const row = object(object(value, "get response").datasheet, "get datasheet")
  if (
    row.datasheet_id !== summary.datasheet_id ||
    row.chip_name !== summary.chip_name
  ) {
    return invalid(
      `detail identity does not match list entry ${summary.datasheet_id}`,
    )
  }
  const recipe = row.footprinter_string
  if (recipe === null || recipe === undefined || recipe === "")
    return { reason: "missing_footprint" }
  if (typeof recipe !== "string")
    return invalid("footprinter_string must be a string or null")
  if (recipe.length > 8192 || !/^[a-z][a-zA-Z0-9.,()+_-]*$/.test(recipe)) {
    return { reason: "nonlocal_or_malformed_footprint" }
  }
  if (
    /padlayout|(?:^|_)profile\(|^memsmic|^lgacav|^microsd_dm3at/i.test(recipe)
  ) {
    return { reason: "nonstandard_footprint" }
  }
  try {
    const datasheet_pdf_urls = strings(
      row.datasheet_pdf_urls,
      "datasheet_pdf_urls",
    )
    for (const url of datasheet_pdf_urls) {
      let parsed: URL
      try {
        parsed = new URL(url)
      } catch {
        return invalid(`invalid datasheet URL for ${summary.chip_name}`)
      }
      if (
        !["http:", "https:"].includes(parsed.protocol) ||
        parsed.username ||
        parsed.password
      ) {
        return invalid(`invalid public datasheet URL for ${summary.chip_name}`)
      }
    }
    const ai_description = string(row.ai_description, "ai_description", true)
    if (!Array.isArray(row.pin_information))
      return invalid("pin_information must be an array")
    const pinIds = new Set<string>()
    const pin_information: DatasheetPinInformation[] = row.pin_information
      .map((entry) => {
        const pin = object(entry, "pin information")
        const pin_number = string(pin.pin_number, "pin_number")
        if (pinIds.has(pin_number))
          return invalid(
            `duplicate physical pin ${pin_number} for ${summary.chip_name}`,
          )
        pinIds.add(pin_number)
        return {
          pin_number,
          name: strings(pin.name, "pin name"),
          description: string(pin.description, "pin description", true),
          capabilities: strings(pin.capabilities, "pin capabilities"),
        }
      })
      .sort((a, b) => compare(a.pin_number, b.pin_number))
    if (pin_information.length === 0)
      return { reason: "missing_pin_information" }
    if (row.pin_attributes === null || row.pin_attributes === undefined) {
      return { reason: "missing_pin_attributes" }
    }
    const pin_attributes = Object.fromEntries(
      Object.entries(object(row.pin_attributes, "pin_attributes")).map(
        ([pin, attributes]) => [
          pin,
          json(
            object(attributes, `pin_attributes.${pin}`),
            `pin_attributes.${pin}`,
          ) as Record<string, JsonValue>,
        ],
      ),
    )
    return {
      part: {
        ...summary,
        datasheet_pdf_urls,
        pin_information,
        ai_description,
        pin_attributes,
        footprinter_string: recipe,
      },
    }
  } catch (error) {
    return { reason: "invalid_metadata", detail: errorDetail(error) }
  }
}

const positiveInteger = (value: number, label: string): number => {
  if (!Number.isSafeInteger(value) || value <= 0)
    return invalid(`${label} must be a positive integer`)
  return value
}

/** Fetch and compile all public records before replacing the generated runtime catalog. */
export const buildDatasheetCatalog = async (
  options: BuildDatasheetCatalogOptions = {},
): Promise<DatasheetCatalogBuildResult> => {
  const apiUrl = (options.apiUrl ?? "https://api.tscircuit.com").replace(
    /\/$/,
    "",
  )
  const api = new URL(apiUrl)
  if (
    !["http:", "https:"].includes(api.protocol) ||
    api.username ||
    api.password ||
    api.search ||
    api.hash
  ) {
    return invalid(
      "API URL must be an HTTP(S) endpoint without credentials, query or fragment",
    )
  }
  const concurrency = positiveInteger(options.concurrency ?? 8, "concurrency")
  if (concurrency > 32) return invalid("concurrency must not exceed 32")
  const requestTimeoutMs = positiveInteger(
    options.requestTimeoutMs ?? 30_000,
    "request timeout",
  )
  const deadlineMs = positiveInteger(
    options.deadlineMs ?? 600_000,
    "build deadline",
  )
  const fetch = options.fetch ?? globalThis.fetch
  const deadline = Date.now() + deadlineMs
  const request = async (
    path: string,
    body: Record<string, string>,
  ): Promise<unknown> => {
    const remaining = deadline - Date.now()
    if (remaining <= 0) return invalid("build deadline exceeded")
    const controller = new AbortController()
    let timer: ReturnType<typeof setTimeout> | undefined
    const timeout = new Promise<never>((_, reject) => {
      timer = setTimeout(
        () => {
          controller.abort()
          reject(
            new Error(
              `Datasheet build failed: request deadline exceeded for ${path}`,
            ),
          )
        },
        Math.min(requestTimeoutMs, remaining),
      )
    })
    try {
      return await Promise.race([
        (async () => {
          const response = await fetch(`${apiUrl}${path}`, {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              "User-Agent": "tscircuit-standalone-catalog",
            },
            body: JSON.stringify(body),
            signal: controller.signal,
          })
          if (!response.ok)
            return invalid(`${path} returned HTTP ${response.status}`)
          let data: unknown
          try {
            data = await response.json()
          } catch {
            return invalid(`${path} returned invalid JSON`)
          }
          await options.onResponse?.(path, body, data)
          return data
        })(),
        timeout,
      ])
    } finally {
      if (timer !== undefined) clearTimeout(timer)
    }
  }
  const listed = parseList(await request("/datasheets/list", {}))
  const parts: BundledPart[] = []
  const exclusions: DatasheetBuildExclusion[] = []
  const compile =
    options.compile ??
    ((part: DatasheetSnapshotPart) =>
      adaptDatasheetPart(
        part,
        normalizeChipName(part.chip_name) === "rp2040" ? "C2040" : undefined,
      ))
  let next = 0
  let failure: unknown
  let failed = false
  const workers = Array.from(
    { length: Math.min(concurrency, listed.length) },
    async () => {
      while (next < listed.length && !failed) {
        const summary = listed[next++]!
        try {
          const { part, reason, detail } = parsePart(
            await request("/datasheets/get", {
              datasheet_id: summary.datasheet_id,
            }),
            summary,
          )
          if (part) {
            try {
              if (!normalizeChipName(part.chip_name))
                throw new Error("Empty normalized chip name")
              const compiled = parseBundledPart(compile(part))
              if (!normalizeChipName(compiled.manufacturerPartNumber))
                throw new Error("Empty normalized manufacturer part number")
              parts.push(compiled)
            } catch (error) {
              exclusions.push({
                ...summary,
                reason: "unsupported_part",
                detail: errorDetail(error),
              })
            }
          } else {
            exclusions.push({
              ...summary,
              reason: reason!,
              ...(detail ? { detail } : {}),
            })
          }
        } catch (error) {
          failed = true
          failure = error
        }
      }
    },
  )
  await Promise.all(workers)
  if (failed) throw failure
  // Detect inventory changes during the build instead of saving an incomplete view.
  const finalList = parseList(await request("/datasheets/list", {}))
  if (serialize(listed) !== serialize(finalList))
    return invalid("datasheet inventory changed during build; retry")
  if (parts.length + exclusions.length !== listed.length)
    return invalid("not every listed datasheet was inspected")
  if (parts.length === 0) return invalid("no usable datasheets were admitted")
  const normalizedNames = new Set<string>()
  for (const entry of parts) {
    const normalized = entry.manufacturerPartNumber
      .replace(/[^0-9a-zA-Z_-]/g, "")
      .toLowerCase()
    if (normalizedNames.has(normalized))
      return invalid(`duplicate normalized manufacturer name ${normalized}`)
    normalizedNames.add(normalized)
  }
  parts.sort((a, b) =>
    compare(
      a.manufacturerPartNumber.toUpperCase(),
      b.manufacturerPartNumber.toUpperCase(),
    ),
  )
  exclusions.sort(
    (a, b) =>
      compare(a.chip_name.toUpperCase(), b.chip_name.toUpperCase()) ||
      compare(a.datasheet_id, b.datasheet_id),
  )
  const encoded = encodeBundledParts(parts)
  if (options.outputPath !== false) {
    await writeBundledPartsModule(
      options.outputPath ??
        resolve(import.meta.dir, "../lib/generated-bundled-parts.ts"),
      encoded.moduleText,
    )
  }
  const exclusionCounts: Record<string, number> = {}
  for (const { reason } of exclusions)
    exclusionCounts[reason] = (exclusionCounts[reason] ?? 0) + 1
  const result = {
    parts,
    ...encoded,
    listedCount: listed.length,
    includedCount: parts.length,
    excludedCount: exclusions.length,
    exclusionCounts,
    exclusions,
  }
  const summary = Object.entries(exclusionCounts)
    .sort(([a], [b]) => compare(a, b))
    .map(([reason, count]) => `${count} ${reason}`)
    .join(", ")
  const log = options.log ?? console.log
  log(
    `Bundled ${parts.length} of ${listed.length} datasheets (${(encoded.gzipBytes / 1024).toFixed(1)} KiB compressed).${summary ? ` Excluded: ${summary}.` : ""}`,
  )
  return result
}

if (import.meta.main) await buildDatasheetCatalog()
